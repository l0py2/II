RecipeViewerEvents.removeEntries('item', event => {
	if(!hideItems) {
		return;
	}

	if(removedItems.length == 0) {
		return;
	}

	removedItems.forEach(item => event.remove(item));
});

ServerEvents.tags('item', event => {
	removedItems.forEach(item => {
		event.removeAllTagsFrom(item);
		event.add('kubejs:removed', item);
	});
});

ServerEvents.tags('block', event => {
	removedItems.forEach(item => {
		if(Item.of(item).getBlock()) {
			event.removeAllTagsFrom(item);
			event.add('kubejs:removed', item);
			event.add('minecraft:mineable/axe', item);
			event.add('minecraft:mineable/pickaxe', item);
		}
	});
});

LootJS.modifiers(event => {
	if(removedItems.length == 0) {
		return;
	}

	const lootTables = event.addTableModifier(/.*/);
	removedItems.forEach(item => lootTables.removeLoot(item));
});

ServerEvents.recipes(event => {
	if(removedItems.length == 0) {
		return;
	}

	removedItems.forEach(removedItem => {
		event.remove({ output: removedItem });
	});
});

ServerEvents.recipes(event => {
	if(removedRecipeTypes.length == 0) {
		return;
	}

	removedRecipeTypes.forEach(recipeType => event.remove({ type: recipeType }));
});
